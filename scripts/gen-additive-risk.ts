// Writes src/domain/additive-risk.ts from the Open Food Facts additives taxonomy.
//
//   bun scripts/gen-additive-risk.ts [--from <path>]
//
// Default: fetch https://static.openfoodfacts.org/data/taxonomies/additives.json
// (requires OFF_USER_AGENT). Use --from to read a local copy instead.

const SOURCE_URL =
    "https://static.openfoodfacts.org/data/taxonomies/additives.json";
const OUT = "src/domain/additive-risk.ts";

type Taxonomy = Record<
    string,
    {
        efsa_evaluation_overexposure_risk?: { en?: string };
    }
>;

type AdditiveRisk = "high" | "moderate" | "none";

function riskFromOff(value: string | undefined): AdditiveRisk | null {
    switch (value) {
        case "en:high":
            return "high";
        case "en:moderate":
            return "moderate";
        case "en:no":
            return "none";
        default:
            return null;
    }
}

function renderMap(entries: [string, AdditiveRisk][]): string {
    const lines = entries.map(([tag, risk]) => `    "${tag}": "${risk}",`);
    return `const ADDITIVE_RISK: Readonly<Record<string, AdditiveRisk>> = {\n${lines.join("\n")}\n};`;
}

function fileBody(
    generatedAt: string,
    entries: [string, AdditiveRisk][],
): string {
    return `// Generated by scripts/gen-additive-risk.ts — do not hand-edit; re-run the script.
// Source: ${SOURCE_URL}
// Generated: ${generatedAt}

export type AdditiveRisk = "high" | "moderate" | "none";

${renderMap(entries)}

export function additiveRisk(tag: string): AdditiveRisk | null {
    const key = tag.trim().toLowerCase();
    return ADDITIVE_RISK[key] ?? null;
}
`;
}

async function loadTaxonomy(fromPath: string | null): Promise<Taxonomy> {
    let raw: string;
    if (fromPath) {
        raw = await Bun.file(fromPath).text();
    } else {
        const ua = process.env.OFF_USER_AGENT;
        if (!ua) {
            throw new Error(
                "OFF_USER_AGENT is not set — required to fetch the additives taxonomy",
            );
        }
        const res = await fetch(SOURCE_URL, {
            headers: { "User-Agent": ua, Accept: "application/json" },
        });
        if (!res.ok) {
            throw new Error(
                `Failed to fetch additives taxonomy: ${res.status}`,
            );
        }
        raw = await res.text();
    }
    return JSON.parse(raw) as Taxonomy;
}

const fromIdx = process.argv.indexOf("--from");
const fromPath = fromIdx >= 0 ? process.argv[fromIdx + 1] : null;
if (fromIdx >= 0 && !fromPath) {
    throw new Error("--from requires a path");
}

const taxonomy = await loadTaxonomy(fromPath);
const entries: [string, AdditiveRisk][] = [];
for (const [tag, meta] of Object.entries(taxonomy)) {
    const risk = riskFromOff(meta.efsa_evaluation_overexposure_risk?.en);
    if (risk) entries.push([tag, risk]);
}
entries.sort((a, b) => a[0].localeCompare(b[0]));

const generatedAt = new Date().toISOString().slice(0, 10);
await Bun.write(OUT, fileBody(generatedAt, entries));
console.log(`wrote ${OUT} (${entries.length} evaluated additives)`);
