// Exports the FigCraft design's variables to design/figcraft-variables.json:
//
//   bun scripts/export-figcraft-variables.ts [path/to/Foodable Design.figcraft]
//
// The design file is read-only: a .figcraft file is a zip, and this only
// streams its document.json out with `unzip -p`. It never writes to, unzips
// beside, or re-saves the design. src/tokens.test.ts compares src/tokens.ts
// to the JSON, so after a design change: re-export, then update the tokens.
//
// Output order is stable: collections and variables in the design's id order,
// modes in the collection's order. Colours are `hex` (#rrggbb) plus `alpha`
// as stored by FigCraft; the export fails if an alpha is not a whole byte,
// because the CSS writes colours as 8-digit hex.
import { homedir } from "node:os";

const DEFAULT_PATH = `${homedir()}/Projects/designs/Foodable/Foodable Design.figcraft`;
const OUT = "design/figcraft-variables.json";

type Rgba = { r: number; g: number; b: number; a: number };
type RawValue =
    | { type: "color"; value: Rgba }
    | { type: "number"; value: number }
    | { type: "string"; value: string }
    | { type: "boolean"; value: boolean };
type RawVariables = {
    collections: {
        id: string;
        name: string;
        modes: { id: string; name: string }[];
    }[];
    variables: {
        id: string;
        name: string;
        collection: string;
        resolvedType: string;
        description?: string;
        values: Record<string, RawValue>;
    }[];
};

const idNum = (id: string) => Number(/(\d+)$/.exec(id)?.[1] ?? NaN);
const byte = (v: number) => Math.round(v * 255);
const hex = (c: Rgba) =>
    "#" +
    [c.r, c.g, c.b].map((v) => byte(v).toString(16).padStart(2, "0")).join("");

function value(name: string, raw: RawValue) {
    if (raw.type !== "color") return raw.value;
    const a = raw.value.a;
    if (Math.abs(a * 255 - byte(a)) > 1e-3) {
        throw new Error(`${name}: alpha ${a} is not a whole byte`);
    }
    return { hex: hex(raw.value), alpha: a };
}

const path = process.argv[2] ?? DEFAULT_PATH;
const doc = JSON.parse(
    await Bun.$`unzip -p ${path} document.json`.quiet().text(),
) as { variables: RawVariables };
const raw = doc.variables;

const collections = [...raw.collections]
    .sort((a, b) => idNum(a.id) - idNum(b.id))
    .map((c) => {
        const variables: Record<string, unknown> = {};
        for (const v of raw.variables
            .filter((v) => v.collection === c.id)
            .sort((a, b) => idNum(a.id) - idNum(b.id))) {
            const values: Record<string, unknown> = {};
            for (const m of c.modes) {
                const r = v.values[m.id];
                if (!r) throw new Error(`${v.name}: no value for ${m.name}`);
                values[m.name] = value(`${v.name} (${m.name})`, r);
            }
            variables[v.name] = {
                type: v.resolvedType,
                description: v.description ?? "",
                values,
            };
        }
        return { name: c.name, modes: c.modes.map((m) => m.name), variables };
    });

await Bun.write(
    OUT,
    JSON.stringify(
        {
            $comment:
                "Generated by scripts/export-figcraft-variables.ts from Foodable Design.figcraft. Do not edit; re-export.",
            collections,
        },
        null,
        4,
    ) + "\n",
);
console.log(`wrote ${OUT}`);
